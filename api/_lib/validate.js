import { HttpError } from './http.js';

const IMG = /\.(png|jpe?g|webp|gif)$/i;
const SEG = /^[A-Za-z0-9][A-Za-z0-9._ %()+-]{0,80}$/;
export const MAX_FILE_BYTES = 3 * 1024 * 1024;

// The only files the admin may write: portfolio screenshots, the profile picture, the resume PDF.
export function checkWritePath(path) {
  if (typeof path !== 'string' || path.length > 220) { throw new HttpError(400, 'Bad path'); }
  if (path === 'public/data.js' || path === 'public/Muhammad-Maheem-Resume.pdf') { return path; }
  const m = path.match(/^public\/(screenshots|profil-pic)\/(.+)$/);
  if (!m) { throw new HttpError(400, 'Path not allowed: ' + path); }
  const segs = m[2].split('/');
  if (segs.length > 4 || !segs.every((s) => s !== '..' && s !== '.' && SEG.test(s))) { throw new HttpError(400, 'Bad path: ' + path); }
  if (!IMG.test(segs[segs.length - 1])) { throw new HttpError(400, 'Only png, jpg, webp or gif images'); }
  return path;
}

export function checkMagic(path, buf) {
  const h = buf.subarray(0, 12);
  const is = (...b) => b.every((x, i) => h[i] === x);
  if (/\.pdf$/i.test(path)) { return is(0x25, 0x50, 0x44, 0x46); }
  if (/\.png$/i.test(path)) { return is(0x89, 0x50, 0x4e, 0x47); }
  if (/\.jpe?g$/i.test(path)) { return is(0xff, 0xd8, 0xff); }
  if (/\.gif$/i.test(path)) { return is(0x47, 0x49, 0x46, 0x38); }
  if (/\.webp$/i.test(path)) { return h.subarray(0, 4).toString() === 'RIFF' && h.subarray(8, 12).toString() === 'WEBP'; }
  return false;
}

export function parseDataJs(text) {
  const i = text.indexOf('window.SITE');
  const eq = text.indexOf('=', i);
  if (i < 0 || eq < 0) { throw new HttpError(500, 'data.js has no window.SITE'); }
  const body = text.slice(eq + 1).trim().replace(/;\s*$/, '');
  try { return JSON.parse(body); } catch { throw new HttpError(500, 'data.js is not pure JSON yet (run scripts/migrate-data.mjs)'); }
}

export function serializeDataJs(site) {
  return '/* Generated by the admin panel. Pure JSON after the first line, so /admin can parse and save it. */\n' +
    'window.SITE = ' + JSON.stringify(site, null, 2) + ';\n';
}

export function validateSite(site) {
  const bad = (m) => { throw new HttpError(400, 'Invalid content: ' + m); };
  if (!site || typeof site !== 'object' || Array.isArray(site)) { bad('not an object'); }
  if (!site.identity || typeof site.identity !== 'object') { bad('identity missing'); }
  ['projects', 'changelog', 'modules', 'socials'].forEach((k) => { if (!Array.isArray(site[k])) { bad(k + ' must be a list'); } });
  if (!site.identity.name) { bad('name is empty'); }
  if (site.projects.some((p) => !p || !p.name)) { bad('a project has no name'); }
  if (JSON.stringify(site).length > 600000) { bad('too large'); }
  // defence in depth: the site also escapes everything, but no link may use a script-capable scheme
  const SAFE = /^(https?:\/\/|mailto:|tel:|[^:]*$)/i;
  const walk = (v, path) => {
    if (Array.isArray(v)) { v.forEach((x, i) => walk(x, path + '[' + i + ']')); return; }
    if (v && typeof v === 'object') {
      Object.keys(v).forEach((k) => {
        if (k === '__proto__' || k === 'constructor' || k === 'prototype') { bad('forbidden key ' + path + '.' + k); }
        if (/^(url|href|link|homepage|adminUrl|banner|image)$/i.test(k) && typeof v[k] === 'string' && v[k].trim() && !SAFE.test(v[k].trim())) {
          bad('unsafe link in ' + path + '.' + k);
        }
        walk(v[k], path + '.' + k);
      });
    }
  };
  walk(site, 'site');
  return site;
}
