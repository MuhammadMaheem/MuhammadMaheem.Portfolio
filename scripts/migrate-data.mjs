// One-time migration: public/data.js (hand-written JS) -> pure JSON, plus the
// new admin fields. Run: node scripts/migrate-data.mjs
// Safe to re-run: already-migrated entries are left alone.
import fs from 'node:fs';
import vm from 'node:vm';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const file = path.join(root, 'public', 'data.js');
const src = fs.readFileSync(file, 'utf8');

const ctx = { window: {} };
vm.createContext(ctx);
vm.runInContext(src, ctx);
const S = ctx.window.SITE;
if (!S) { throw new Error('data.js did not define window.SITE'); }

const MONTHS = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'];
const slug = (t) => String(t).toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '').slice(0, 48);

// "Jun 2026" -> "2026-06", "2024" -> "2024"
function parsePart(t) {
  const s = String(t || '').trim();
  const m = s.match(/^([A-Za-z]{3})[a-z]*\s+(\d{4})$/);
  if (m) {
    const i = MONTHS.findIndex((x) => x.toLowerCase() === m[1].toLowerCase());
    return i >= 0 ? m[2] + '-' + String(i + 1).padStart(2, '0') : s;
  }
  return s;
}

// ---- experience ----
const seen = new Set();
(S.changelog || []).forEach((c) => {
  if (!c.id) {
    let id = slug(c.org);
    while (seen.has(id)) { id += '-2'; }
    c.id = id;
  }
  seen.add(c.id);
  if (!c.type) { c.type = /bachelor|degree|university/i.test(c.role) ? 'education' : 'internship'; }
  if (!c.start && c.date) {
    const [a, b] = c.date.split(/\s*[—–-]\s*/);
    c.start = parsePart(a);
    c.end = parsePart(b);
    c.present = false;
  }
  if (!c.format) { c.format = 'paragraph'; }
  delete c.date; // derived from start/end
  delete c.v; // derived from position
});

// ---- projects ----
(S.projects || []).forEach((p) => {
  if (!p.placement) { p.placement = p.showcase ? 'flagship' : (p.featured ? 'featured' : 'normal'); }
  delete p.featured; // replaced by placement
});

// ---- writing: no article behind these yet, so no url ----
(S.writing || []).forEach((w) => { if (w.url === undefined) { w.url = ''; } });

// ---- section headings (text that used to live in index.html) ----
if (!S.sections) {
  S.sections = {
    about: { nav: 'About', eyebrow: 'About', title: 'Behind the unit,\na real person.', sub: '', visible: true },
    skills: { nav: 'Skills', eyebrow: 'Skills', title: 'Technical Arsenal.', sub: 'Core systems grouped by domain. Hover to explore depth.', visible: true },
    projects: {
      nav: 'Projects', eyebrow: 'Projects', title: 'Things I shipped.',
      sub: "Two I'm proudest of first, then the rest: LLM evaluation, RAG systems, legal & HR AI tools, computer vision, and full-stack AI products.",
      visible: true,
    },
    experience: { nav: 'Experience', eyebrow: 'Experience', title: 'How I got here.', sub: '', visible: true },
    writing: { nav: 'Writing', eyebrow: 'Writing', title: 'Things I wrote down.', sub: 'Notes from the field — mostly about making AI behave in production.', visible: true },
    contact: { nav: 'Contact', eyebrow: 'Contact', title: "Let's build\n*something*.", sub: 'Hiring, collaborating, or just want to argue about evals? My inbox is open.', visible: true },
  };
}

fs.writeFileSync(
  file,
  '/* Generated by the admin panel (or scripts/migrate-data.mjs). Pure JSON after the first line, so it can be parsed and saved by /admin. */\n' +
    'window.SITE = ' + JSON.stringify(S, null, 2) + ';\n',
);
console.log('migrated', S.projects.length, 'projects,', S.changelog.length, 'experience entries');
